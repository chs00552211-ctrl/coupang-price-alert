function hasWord(text, words) {
  const t = ` ${text} `.toLowerCase();
  return words.some((w) => t.includes(w.toLowerCase()));
}

/**
 * @param {string} name 상품 이름이나 글 제목
 * @param {string} [category] 쿠팡/커뮤니티가 알려준 카테고리 이름
 */
export function classify(name, category = '') {
  if (category) {
    if (IT_CATEGORY.test(category)) return 'IT';
    if (FOOD_CATEGORY.test(category)) return '식품';
  }
  const it = hasWord(name, IT_WORDS);
  const food = hasWord(name, FOOD_WORDS);
  if (it && !food) return 'IT';
  if (food && !it) return '식품';
  if (it && food) {
    // "ml", "kg" 같은 단위만 겹친 경우엔 IT 단어 쪽을 믿어요.
    return hasWord(name, FOOD_WORDS.filter((w) => w !== 'kg' && w !== 'ml')) ? '식품' : 'IT';
  }
  return '기타';
}
